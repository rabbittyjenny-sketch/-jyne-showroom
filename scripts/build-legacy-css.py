"""Copies the <style> of each ORIGINAL island page verbatim into src/legacy/legacy.css,
scoped under .lg-<preset> so new island pages look exactly like the originals.
Every preset gets about_island.html's rules first (the shared card family), then its own page's rules.
Run:  python3 scripts/build-legacy-css.py <folder with the original .html pages>"""
import re, sys, pathlib

SRC = pathlib.Path(sys.argv[1])
OUT = pathlib.Path(__file__).resolve().parent.parent / 'src/legacy/legacy.css'
PAGES = {
    'about': 'about_island.html', 'marina': 'work_marina.html', 'works': 'work_town.html',
    'learning': 'learning_bay.html', 'district': 'system_district.html', 'blog': 'blog.html',
    'contact': 'contact_port.html',
}

def styles(html):
    return '\n'.join(re.findall(r'<style[^>]*>(.*?)</style>', html, re.S))

def blocks(css):
    """yield (prelude, body) for top-level blocks; comments removed"""
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    i, n = 0, len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0: break
        prelude = css[i:j].strip()
        depth, k = 1, j + 1
        while k < n and depth:
            if css[k] == '{': depth += 1
            elif css[k] == '}': depth -= 1
            k += 1
        yield prelude, css[j + 1:k - 1]
        i = k

def scope_sel(sel, w):
    s = sel.strip()
    if not s: return s
    if s in ('body', 'html', ':root'): return w
    m = re.match(r'^(body|html)([.:#\[].*)$', s)          # body.lang-en .x
    if m: return w + m.group(2)
    m = re.match(r'^(body|html)\s+(.*)$', s)               # body .x
    if m: return f'{w} {m.group(2)}'
    return f'{w} {s}'

def scope(css, w, tag):
    out = []
    frames = set(re.findall(r'@keyframes\s+([\w-]+)', css))
    for prelude, body in blocks(css):
        if prelude.startswith('@media') or prelude.startswith('@supports'):
            out.append(f'{prelude} {{\n{scope(body, w, tag)}\n}}')
        elif prelude.startswith('@keyframes'):
            name = prelude.split()[1]
            out.append(f'@keyframes {name}-{tag} {{{body}}}')
        elif prelude.startswith('@'):
            out.append(f'{prelude} {{{body}}}')
        else:
            sels = ', '.join(scope_sel(s, w) for s in prelude.split(','))
            out.append(f'{sels} {{{body}}}')
    text = '\n'.join(out)
    for f in frames:   # point animations at the renamed keyframes of this page
        text = re.sub(rf'(animation[^;{{}}]*?)\b{re.escape(f)}\b(?!-)', rf'\g<1>{f}-{tag}', text)
    return text

base_css = styles((SRC / PAGES['about']).read_text(encoding='utf-8'))
# the shared base is also used by non-orange pages: its few hard-coded orange values follow --accent
base_shared = base_css.replace('#B03A00', 'var(--accent)')
_root = re.search(r':root\s*\{[^}]*\}', base_css).group(0)          # keep the real default values
base_shared = re.sub(r':root\s*\{[^}]*\}', lambda m: _root, base_shared, count=1)

parts = ['/* GENERATED by scripts/build-legacy-css.py from the original island pages — do not edit by hand. */']
for preset, file in PAGES.items():
    w = f'.lg.lg-{preset}'
    own = styles((SRC / file).read_text(encoding='utf-8'))
    parts.append(f'\n/* ===== {preset}: base (about_island.html) ===== */')
    parts.append(scope(base_css if preset == 'about' else base_shared, w, f'{preset}-base'))
    if preset != 'about':
        parts.append(f'\n/* ===== {preset}: {file} ===== */')
        parts.append(scope(own, w, preset))
OUT.write_text('\n'.join(parts) + '\n', encoding='utf-8')
print(OUT, OUT.stat().st_size)
