// Builds supabase/migrations/20261030120100_i365_seed.sql from seed/seed.json.
// seed.json is the only place the starting data lives; the website's mock mode
// reads the same file, so the two can never disagree.
// Every insert is "on conflict do nothing": running it twice changes nothing,
// and it never overwrites what you have since edited in the back office.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const seed = JSON.parse(readFileSync(join(root, 'seed/seed.json'), 'utf8'));

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => `${q(JSON.stringify(v ?? {}))}::jsonb`;
const n = (v) => (v === null || v === undefined ? 'null' : Number(v));
const out = [];
const add = (s) => out.push(s);

add('-- GENERATED by scripts/build-seed-sql.mjs from seed/seed.json — edit seed.json, not this file.');
add('-- Safe to re-run: every insert skips rows that already exist.\n');

for (const [key, value] of Object.entries(seed.site_settings)) {
  add(`insert into public.i365_site_settings (key, value) values (${q(key)}, ${j(value)}) on conflict (key) do nothing;`);
}

seed.island_templates.forEach((t, i) => {
  add(`insert into public.i365_island_templates (slug, name_th, name_en, icon, default_features, sort_order)
values (${q(t.slug)}, ${q(t.name_th)}, ${q(t.name_en)}, ${q(t.icon)}, ${j(t.default_features)}, ${i + 1})
on conflict (slug) do nothing;`);
});

seed.item_types.forEach((t, i) => {
  add(`insert into public.i365_item_types (slug, name_th, name_en, fields, features, default_display, sort_order)
values (${q(t.slug)}, ${q(t.name_th)}, ${q(t.name_en)}, ${q(JSON.stringify(t.fields))}::jsonb, ${j(t.features)}, ${q(t.default_display)}, ${i + 1})
on conflict (slug) do nothing;`);
});

seed.tag_groups.forEach((g, i) => {
  add(`insert into public.i365_tag_groups (slug, name_th, name_en, allow_multiple, sort_order)
values (${q(g.slug)}, ${q(g.name_th)}, ${q(g.name_en)}, ${g.allow_multiple}, ${i + 1})
on conflict (slug) do nothing;`);
  g.tags.forEach(([slug, th, en], k) => {
    add(`insert into public.i365_tags (group_id, slug, name_th, name_en, sort_order)
select id, ${q(slug)}, ${q(th)}, ${q(en)}, ${k + 1} from public.i365_tag_groups where slug = ${q(g.slug)}
on conflict (group_id, slug) do nothing;`);
  });
});

const templates = Object.fromEntries(seed.island_templates.map((t) => [t.slug, t]));
for (const isl of seed.islands) {
  const [left, top, width] = isl.pos ?? [null, null, null];
  add(`insert into public.i365_islands (slug, template_id, name_th, name_en, tooltip_th, intro_th, features,
  button_image, land_image, pos_left, pos_top, pos_width, redirect_url, is_published, sort_order)
select ${q(isl.slug)}, t.id, ${q(isl.name_th)}, ${q(isl.name_en)}, ${q(isl.tooltip_th)}, ${q(isl.intro_th)},
  ${j(templates[isl.template].default_features)}, ${q(isl.button_image)}, ${q(isl.land_image)},
  ${n(left)}, ${n(top)}, ${n(width)}, ${q(isl.redirect_url)}, true, ${isl.sort_order}
from public.i365_island_templates t where t.slug = ${q(isl.template)}
on conflict (slug) do nothing;`);

  isl.sections.forEach((s, i) => {
    const [sl, st, sw] = s.pos ?? [null, null, null];
    const source = s.source_type ?? 'items';
    const button = `/islands/${isl.slug}/btn-${s.slug}.png`;
    add(`insert into public.i365_sections (island_id, slug, name_th, name_en, item_type_id, source_type,
  display_style, button_image, pos_left, pos_top, pos_width, is_published, sort_order)
select i.id, ${q(s.slug)}, ${q(s.name_th)}, ${q(s.name_en)},
  ${s.item_type ? `(select id from public.i365_item_types where slug = ${q(s.item_type)})` : 'null'},
  ${q(source)}, ${q(s.display)}, ${q(button)}, ${n(sl)}, ${n(st)}, ${n(sw)}, true, ${i + 1}
from public.i365_islands i where i.slug = ${q(isl.slug)}
on conflict (island_id, slug) do nothing;`);
  });
}

seed.routes.forEach((r, i) => {
  add(`insert into public.i365_routes (slug, title_th, title_en, headline_th, is_published, sort_order)
values (${q(r.slug)}, ${q(r.title_th)}, ${q(r.title_en)}, ${q(r.headline_th)}, true, ${i + 1})
on conflict (slug) do nothing;`);
  for (const [slug, th, en] of r.variants) {
    add(`insert into public.i365_route_variants (route_id, slug, title_th, title_en)
select id, ${q(slug)}, ${q(th)}, ${q(en)} from public.i365_routes where slug = ${q(r.slug)}
on conflict (slug) do nothing;`);
  }
});

(seed.items ?? []).forEach((it, i) => {
  // re-run safe: a clip is matched by its link, anything else by its title within the same section
  const dup = it.data.video_url
    ? `x.data->>'video_url' = ${q(it.data.video_url)}`
    : `x.title_th = ${q(it.title_th)}`;
  add(`insert into public.i365_items (section_id, item_type_id, title_th, title_en, summary_th, cover_image, data, is_published, sort_order)
select s.id, s.item_type_id, ${q(it.title_th)}, ${q(it.title_en ?? null)}, ${q(it.summary_th ?? null)}, ${q(it.cover_image ?? null)}, ${j(it.data)}, ${it.is_published === false ? 'false' : 'true'}, ${i + 1}
from public.i365_sections s join public.i365_islands isl on isl.id = s.island_id
where isl.slug = ${q(it.island)} and s.slug = ${q(it.section)}
  and not exists (select 1 from public.i365_items x where x.section_id = s.id and ${dup});`);
});

const file = join(root, 'supabase/migrations/20261030120100_i365_seed.sql');
writeFileSync(file, out.join('\n') + '\n');
console.log(`wrote ${file} (${out.length} statements)`);
