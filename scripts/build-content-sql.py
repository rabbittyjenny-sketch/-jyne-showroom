"""Writes supabase/data/i365_current_page_content.sql: the content the live pages show today, taken from the
original page files, as back office items (so the back office starts with exactly what the site shows).
Run from the repo root:  python3 scripts/build-content-sql.py
"""
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
src = lambda f: (ROOT / f).read_text(encoding='utf-8')
A, M, WT = src('about_island.html'), src('work_marina.html'), src('work_town.html')


def between(t, a, b):
    i = t.index(a); return t[i:t.index(b, i)]


prev = re.findall(r'<img src="([^"]+)"', between(A, '<!-- SALES FIGURES -->', '<!-- RESUME -->'))
resume = re.search(r'src="([^"]+)"\s+alt="Jyne Resume', A).group(1)
live_shots = re.findall(r'<img src="(https://ik\.imagekit\.io/ideas365logo/Screenshot%202026[^"]+)"', A)
proofs = re.findall(r'<img src="(https://ik\.imagekit\.io/ideas365logo/proof\d\.jpg)" alt="([^"]*)"', WT)
clips_live = re.findall(r'<a href="(https://www\.youtube\.com/watch\?v=[\w-]+)"', between(M, '<!-- 4. PORTFOLIO MEDIA -->', '<!-- 5. AI VOICE GENERATOR -->'))
clips_voice = re.findall(r'<a href="(https://www\.youtube\.com/watch\?v=[\w-]+)"', between(M, '<!-- 5. AI VOICE GENERATOR -->', '    </main>'))
assert len(prev) == 8 and len(live_shots) == 4 and len(proofs) == 4 and len(clips_live) == 11 and len(clips_voice) == 5, \
    (len(prev), len(live_shots), len(proofs), len(clips_live), len(clips_voice))

E = lambda v, t, **kw: dict(v=v, t=t, **kw)
blocks = [
    ('about', 'previous-work', 'image', 'about_experience · PREVIOUS WORK EXPERIENCE', [E(u, f'งานที่ผ่านมา #{i}') for i, u in enumerate(prev, 1)]),
    ('about', 'resume', 'file_url', 'about_experience · RESUME (รูป + ปุ่มดาวน์โหลด)', [E(resume, 'เรซูเม่', d={'language': 'th'})]),
    ('about', 'live-proof', 'image', 'about_live · RESULT · 2 HRS/LIVE', [E(u, a, d={'caption_th': a}) for u, a in proofs]),
    ('works', 'live-selling', 'video_url', 'works_clips · PORTFOLIO MEDIA', [E(u, f'ไลฟ์ขาย #{i}', d={'platform': 'youtube'}) for i, u in enumerate(clips_live, 1)]),
    ('works', 'ai-voice', 'video_url', 'works_clips · AI VOICE GENERATOR', [E(u, f'AI Voice · Avatar #{i}', d={'platform': 'youtube'}) for i, u in enumerate(clips_voice, 1)]),
    ('works', 'makeup-hair', 'image', 'works_photos · MAKEUP & HAIR', [E('https://ik.imagekit.io/ideas365logo/makeup1.jpg', 'งานแต่งหน้า #1')]),
    ('works', 'live-results', 'image', 'works_photos · LIVE RESULTS', [E(u, f'ผลไลฟ์ 2 ชม. #{i}') for i, u in enumerate(live_shots, 1)]),
    ('learning', 'web-design', 'url', 'learning_design · WEB DESIGN', [E('https://adminccl.wixsite.com/a-little-bit-idea-2/home', 'A Little Bit Idea (Wix)',
                                                                         s='เว็บไซต์ที่ออกแบบและทำเองบน Wix', d={'tools': 'Wix.com'})]),
]

q = lambda s: "'" + s.replace("'", "''") + "'"
out = [f"""-- iDEAS365 · content the pages show today → back office items (generated by scripts/build-content-sql.py)
--
-- Run in Supabase → SQL Editor AFTER migration 20261102090000_i365_match_site_pages.sql (already applied).
-- Safe to run again: items are matched by their link/image, updated in place, never duplicated.
-- After this runs, these topics are shown from the database (same pictures / clips, same order as now);
-- add / hide / reorder them in the back office from then on.
-- Items that were in these topics but are not on the page today are hidden (is_published = false), not deleted.
--
-- NOT included (the page loads them from the Google Sheet, which is not reachable from here):
--   learning_tools  (sheets work_ai / work_commerce / work_creative) and learning_docs (sheet Sheet1)
--   → they keep loading from the sheet until items are published in those sections. A template is at the end.

begin;

create or replace function pg_temp.i365_put(_island text, _section text, _key text, _entries jsonb)
returns void language plpgsql as $$
declare s record; e jsonb; n int := 0; found_id uuid;
begin
  select sec.id, sec.item_type_id into s
  from public.i365_sections sec join public.i365_islands i on i.id = sec.island_id
  where i.slug = _island and sec.slug = _section and sec.deleted_at is null;
  if s.id is null then raise exception 'section %/% not found — run the migration first', _island, _section; end if;

  for e in select * from jsonb_array_elements(_entries) loop
    n := n + 1;
    select id into found_id from public.i365_items where section_id = s.id and data->>_key = e->>'v' order by created_at limit 1;
    if found_id is null then
      insert into public.i365_items (section_id, item_type_id, title_th, summary_th, data, is_published, sort_order)
      values (s.id, s.item_type_id, e->>'t', e->>'s', jsonb_build_object(_key, e->>'v') || coalesce(e->'d', '{{}}'::jsonb), true, n);
    else
      update public.i365_items set title_th = e->>'t', summary_th = coalesce(e->>'s', summary_th),
        data = data || jsonb_build_object(_key, e->>'v') || coalesce(e->'d', '{{}}'::jsonb),
        is_published = true, sort_order = n, updated_at = now()
      where id = found_id;
    end if;
  end loop;

  -- anything else in this topic is not on the page today: hide it (kept in the back office)
  update public.i365_items set is_published = false, updated_at = now()
  where section_id = s.id and is_published
    and not (data->>_key in (select x->>'v' from jsonb_array_elements(_entries) x));
end $$;

-- pictures that were imported into other topics: move them to the topic whose page shows them now
update public.i365_items it set section_id = dst.id, updated_at = now()
from public.i365_sections src_s, public.i365_sections dst, public.i365_islands i
where it.section_id = src_s.id and src_s.slug = 'booth-event' and src_s.island_id = i.id and i.slug = 'works'
  and dst.slug = 'previous-work' and dst.island_id = (select id from public.i365_islands where slug = 'about');

update public.i365_items it set section_id = dst.id, updated_at = now()
from public.i365_sections src_s, public.i365_sections dst, public.i365_islands i
where it.section_id = src_s.id and src_s.slug = 'live-results' and src_s.island_id = i.id and i.slug = 'works'
  and it.data->>'image' ~ '/proof[0-9]\\.jpg$'
  and dst.slug = 'live-proof' and dst.island_id = (select id from public.i365_islands where slug = 'about');
"""]
for isl, sec, key, label, entries in blocks:
    out.append(f"\n-- {label}  ({len(entries)})\nselect pg_temp.i365_put('{isl}', '{sec}', '{key}', {q(json.dumps(entries, ensure_ascii=False, indent=1))}::jsonb);\n")
out.append("""
commit;

-- check: what each page will now take from the database
select s.page_slug, s.slug as section, count(it.*) filter (where it.is_published and s.is_published) as shown_from_db
from public.i365_sections s left join public.i365_items it on it.section_id = s.id
where s.deleted_at is null and s.page_slug is not null
group by s.page_slug, s.slug, s.sort_order order by s.page_slug, s.sort_order;

-- ── TEMPLATE (not run): a tool card for learning_tools, same fields as the Google Sheet ──────────────
-- Publishing even one item in a tools section makes that grid show the database instead of the sheet,
-- so enter all of that grid's tools (back office → AI&TECH CREATION BRIDGE → AI TOOLS & ASTROLOGY → ผลงาน).
-- insert into public.i365_items (section_id, item_type_id, title_th, title_en, summary_th, cover_image, data, is_published, sort_order)
-- select s.id, s.item_type_id, 'ชื่อไทย', 'English title', 'คำอธิบาย', 'https://…/cover.png',
--        '{"url":"https://…","category":"ai","status":"live","logo":"https://…/logo.png"}'::jsonb, true, 1
-- from public.i365_sections s join public.i365_islands i on i.id = s.island_id
-- where i.slug = 'learning' and s.slug = 'tools-ai';   -- tools-commerce / tools-creative
""")
p = ROOT / 'supabase/data/i365_current_page_content.sql'
p.write_text(''.join(out), encoding='utf-8')
print('wrote', p, sum(len(b[4]) for b in blocks), 'items')
